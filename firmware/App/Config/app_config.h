/* ---- 电机/编码器方向：**分侧**开关（2026-10-13 真机数据定案）----
 * 实测证据（tools/fw_prep/out/tilt.log）：前后倾时 `spd L` 与 `spd R`
 * **幅值几乎相等、符号永远相反**（前倾 −115/+115，后倾 +484/−485）——
 * 平衡车前倾时两轮应当**同向往前追**，现在是"原地对拧" ⇒ 车只会扭转、重心继续倒，
 * 这正是"奔着跌倒去"的根源。它不是"整体符号翻一个"的问题，而是
 * **左右两侧彼此不一致**（一侧的电机或编码器相对另一侧接反）。
 * 顺带：左右压（转向）时两轮反向是**正常**的，所以问题只在共模动作上。
 *
 * 接线约定（用户实测）：CN1 = 左轮 → Moto1；CN2 = 右轮 → Moto2。
 * 处置顺序（一次只动一个，动完烧一次做倾斜测试）：
 *   ① 两轮**反向对拧**（一个往前一个往后） ⇒ 电机有一侧反 ⇒ 翻 CFG_MOTOR_*_INVERT
 *   ② 两轮**同向**但车往反方向跑（前倾却往后走） ⇒ 编码器有一侧反 ⇒ 翻 CFG_ENCODER_*_INVERT
 * 当前取值：右轮电机翻向（按"最可能是一侧电机接线反了"先试这个）。*/
